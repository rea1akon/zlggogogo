// 访客隐私脱敏正则单测（与 cloud-sync.js 中保持一致）
var PRIVACY_ID18_RE = /(^|[^0-9a-zA-Z*])(\d{6})(\d{4})(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])(\d{3}[0-9Xx])(?![0-9a-zA-Z*])/g;
var PRIVACY_ID15_RE = /(^|[^0-9a-zA-Z*])(\d{6})(\d{2})(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])(\d{3})(?![0-9a-zA-Z*])/g;
var PRIVACY_PHONE_RE = /(^|[^0-9a-zA-Z*])(1[3-9]\d)(\d{4})(\d{4})(?![0-9a-zA-Z*])/g;

function mask(t) {
  if (!t || t.length < 11) return t;
  return t
    .replace(PRIVACY_ID18_RE, '$1$2********$6')
    .replace(PRIVACY_ID15_RE, '$1$2******$6')
    .replace(PRIVACY_PHONE_RE, '$1$2****$4');
}

var cases = [
  // [输入, 期望输出, 说明]
  ['412902197808303541', '412902********3541', '18位身份证(纯文本)'],
  ['身份证号：412902197808303541。', '身份证号：412902********3541。', '18位身份证(夹在中文里)'],
  ['41290219780830354X', '412902********354X', '18位身份证(X校验位)'],
  ['412902780830354', '412902******354', '15位老身份证'],
  ['13812345678', '138****5678', '手机号(纯文本)'],
  ['联系电话 13812345678 请查收', '联系电话 138****5678 请查收', '手机号(夹在中文里)'],
  ['2026/09/10', '2026/09/10', '日期不误伤'],
  ['2030/5/31', '2030/5/31', '短日期不误伤'],
  ['编号123456', '编号123456', '6位编号不误伤'],
  ['订单号 9876543210123', '订单号 9876543210123', '13位普通数字(非身份证格式)不误伤'],
  ['412902********3541', '412902********3541', '已掩码文本幂等(不变)'],
  ['138****5678', '138****5678', '已掩码手机幂等(不变)'],
  ['1378083035412', '1378083035412', '12位数字非手机号不误伤'],
  ['年龄48', '年龄48', '普通短文本不变'],
];

var fail = 0;
for (var i = 0; i < cases.length; i++) {
  var got = mask(cases[i][0]);
  var ok = got === cases[i][1];
  if (!ok) fail++;
  console.log((ok ? 'PASS' : 'FAIL') + ' | ' + cases[i][2] + ' | ' + cases[i][0] + ' -> ' + got + (ok ? '' : ' (期望 ' + cases[i][1] + ')'));
}
console.log(fail === 0 ? '\n全部通过' : '\n有 ' + fail + ' 例失败');
process.exit(fail === 0 ? 0 : 1);
